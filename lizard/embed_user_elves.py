#!/usr/bin/env python3
"""Generate embed_hello.c with one or more name:path ELF blobs for TigFS seed."""
import sys

def main():
    # args: path:fsname  path:fsname ...
    entries = []
    for arg in sys.argv[1:]:
        if ':' not in arg:
            raise SystemExit(f"need path:fsname, got {arg}")
        path, name = arg.split(':', 1)
        data = open(path, 'rb').read()
        entries.append((name, data))

    print('/* auto-generated by lizard/embed_user_elves.py — do not edit */')
    print('#include <stddef.h>')
    print('#include <stdint.h>')
    print()
    for i, (name, data) in enumerate(entries):
        print(f'static const unsigned char emb_{i}[] = {{')
        print(','.join(f'0x{b:02x}' for b in data))
        print('};')
        print()

    print('struct embedded_elf {')
    print('    const char *name;')
    print('    const unsigned char *data;')
    print('    unsigned int len;')
    print('};')
    print()
    print('const struct embedded_elf embedded_elves[] = {')
    for i, (name, data) in enumerate(entries):
        print(f'    {{ "{name}", emb_{i}, {len(data)} }},')
    print('};')
    print(f'const unsigned int embedded_elves_count = {len(entries)};')
    print()
    # Back-compat symbols for any old references
    if entries:
        print('const unsigned char *embedded_hello_elf = emb_0;')
        print(f'const unsigned int embedded_hello_elf_len = {len(entries[0][1])};')

if __name__ == '__main__':
    main()
